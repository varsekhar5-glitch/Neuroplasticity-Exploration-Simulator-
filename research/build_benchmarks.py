#!/usr/bin/env python3
"""Phase-1 literature pipeline: research/literature.csv -> benchmarks.json.

Conversion rule (same as documented in app.js): a standardized effect size
(Cohen's d / Hedges' g / SMD) maps to model points as round(effect * 20) on the
illustrative 0-100 scale; a direct percent-change is used as-is. Rows whose
result is not statistically significant (CI crosses zero or direction is
null-effect) are flagged so the model keeps them near zero.

Run:  python3 research/build_benchmarks.py
Writes benchmarks.json at the project root (loaded by app.js at boot).
"""
import csv, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "research" / "literature.csv"
OUT = ROOT / "benchmarks.json"

STD_TYPES = {"cohens-d", "hedges-g", "SMD"}

def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None

def main():
    rows = list(csv.DictReader(SRC.open(encoding="utf-8")))
    coefficients, benchmarks, context = {}, {}, []
    for r in rows:
        target = (r.get("model_target") or "").strip()
        eff, lo, hi = num(r.get("effect_value")), num(r.get("ci_low")), num(r.get("ci_high"))
        significant = not (
            r.get("direction") == "null-effect"
            or (lo is not None and hi is not None and lo <= 0 <= hi)
        )
        entry = {
            "study_id": r["study_id"], "citation": r["citation"],
            "source_type": r["source_type"], "population": r["population"],
            "n": num(r.get("n")), "intervention": r["intervention"],
            "outcome": r["outcome"], "effect_type": r["effect_type"],
            "effect_value": eff, "ci": [lo, hi],
            "significant": significant, "confidence": r["confidence"],
            "disease_match": r["disease_match"], "notes": r["notes"],
        }
        if r["effect_type"] in STD_TYPES and eff is not None:
            entry["model_points"] = round(eff * 20) if significant else round(eff * 20 / 7) or 0
            entry["conversion"] = "effect*20 (near-zero if not significant)"
        elif r["effect_type"] == "percent-change" and eff is not None:
            entry["model_points"] = round(eff)
            entry["conversion"] = "direct percent"
        if target.startswith("coef."):
            coefficients.setdefault(target[5:], []).append(entry)
        elif target.startswith("bench."):
            benchmarks.setdefault(target[6:], []).append(entry)
        else:
            context.append(entry)

    out = {
        "note": "Generated by research/build_benchmarks.py from research/literature.csv. Edit the CSV, not this file.",
        "n_sources": len({r["study_id"] for r in rows}),
        "coefficients": coefficients,
        "benchmarks": benchmarks,
        "context": context,
    }
    OUT.write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"{OUT.name}: {len(rows)} rows, {out['n_sources']} sources, "
          f"{len(coefficients)} coefficient targets, {len(benchmarks)} benchmark targets")

if __name__ == "__main__":
    sys.exit(main())
